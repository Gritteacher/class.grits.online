import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const db = new PGlite();
const teacher = '10000000-0000-4000-8000-000000000001', other = '10000000-0000-4000-8000-000000000002';
const one = '20000000-0000-4000-8000-000000000001', two = '20000000-0000-4000-8000-000000000002', archived = '20000000-0000-4000-8000-000000000003';
const room = '30000000-0000-4000-8000-000000000001', otherRoom = '30000000-0000-4000-8000-000000000002';
const id = () => crypto.randomUUID();
const q = async (sql, params = []) => (await db.query(sql, params)).rows;
const as = async user => { await db.exec('reset role'); await q("select set_config('request.jwt.claim.sub',$1,false)", [user]); await db.exec('set role authenticated'); };
try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema auth to authenticated,anon; grant execute on function auth.uid() to authenticated,anon;
    create table public.profiles(id uuid primary key,role text,display_name text,status text default 'active');
    create table public.classrooms(id uuid primary key,name text,teacher_id uuid references profiles(id));
    create table public.classroom_members(classroom_id uuid references classrooms(id),student_id uuid references profiles(id) on delete cascade,student_number integer);
    create table public.attendance_records(classroom_id uuid,student_id uuid,attendance_date date,period smallint,status text);
    grant select on public.profiles,public.classrooms,public.classroom_members,public.attendance_records to authenticated;
    insert into profiles(id,role,display_name,status) values
    ('${teacher}','teacher','Teacher','active'),('${other}','teacher','Other','active'),('${one}','student','One','active'),('${two}','student','Two','active'),('${archived}','student','Archived','archived');
    insert into classrooms values('${room}','Duplicate name','${teacher}'),('${otherRoom}','Duplicate name','${other}');
    insert into classroom_members values('${room}','${one}',1),('${room}','${two}',2),('${room}','${archived}',3);
    insert into attendance_records values('${room}','${one}','2026-11-19',1,'present'),('${room}','${two}','2026-11-19',1,'absent');`);
  await db.exec(readFileSync('supabase/migrations/20261119033941_classroom_wheel_rewards.sql', 'utf8'));
  await as(teacher);
  const roundId = id(), drawId = id();
  const start = () => q('select public.start_classroom_wheel_round($1,$2,$3,false,null,null) as value', [roundId, room, [one, two]]);
  await start(); await start();
  assert.equal((await q('select count(*)::int as n from classroom_wheel_rounds'))[0].n, 1);
  const first = (await q('select public.spin_classroom_wheel($1,$2) as value', [roundId, drawId]))[0].value;
  assert.equal((await q('select public.spin_classroom_wheel($1,$2) as value', [roundId, drawId]))[0].value.student_id, first.student_id);
  const second = (await q('select public.spin_classroom_wheel($1,$2) as value', [roundId, id()]))[0].value;
  assert.notEqual(second.student_id, first.student_id);
  await assert.rejects(q('select public.spin_classroom_wheel($1,$2)', [roundId, id()]), /ครบทุกคน/);
  await assert.rejects(q('select public.award_classroom_reinforcement($1,$2,101,$3)', [drawId, id(), 'Bad']), /1–100/);
  const award = (await q('select public.award_classroom_reinforcement($1,$2,3,$3) as value', [drawId, id(), 'Participation']))[0].value;
  const duplicate = (await q('select public.award_classroom_reinforcement($1,$2,5,$3) as value', [drawId, id(), 'Different retry']))[0].value;
  assert.equal(duplicate.id, award.id);
  assert.equal(duplicate.points, 3);
  assert.equal((await q('select public.student_reinforcement_summary($1) as value', [first.student_id]))[0].value.total, 3);
  await assert.rejects(q("insert into student_reinforcement_entries(student_id,teacher_id,classroom_id,points,reason,teacher_name) values($1,$2,$3,100,'tamper','x')", [one, teacher, room]), /permission denied/);
  await as(first.student_id);
  assert.equal((await q('select count(*)::int as n from student_reinforcement_entries'))[0].n, 1);
  await assert.rejects(q('select public.spin_classroom_wheel($1,$2)', [roundId, id()]), /ไม่มีสิทธิ์/);
  await assert.rejects(q('select public.student_reinforcement_summary($1)', [second.student_id]), /ไม่มีสิทธิ์/);
  await as(second.student_id);
  assert.equal((await q('select count(*)::int as n from student_reinforcement_entries'))[0].n, 0);
  await as(other);
  assert.equal((await q('select count(*)::int as n from classroom_wheel_rounds'))[0].n, 0);
  await assert.rejects(q('select public.start_classroom_wheel_round($1,$2,$3,false,null,null)', [id(), room, [one]]), /ไม่มีสิทธิ์/);
  await assert.rejects(q('select public.reverse_classroom_reinforcement($1,$2)', [award.id, 'Wrong teacher']), /ไม่มีสิทธิ์/);
  await as(teacher);
  const reversal = (await q('select public.reverse_classroom_reinforcement($1,$2) as value', [award.id, 'Correction']))[0].value;
  assert.equal(reversal.points, -3);
  assert.equal((await q('select public.reverse_classroom_reinforcement($1,$2) as value', [award.id, 'Retry']))[0].value.id, reversal.id);
  assert.equal((await q('select public.student_reinforcement_summary($1) as value', [first.student_id]))[0].value.total, 0);
  await assert.rejects(q('select public.start_classroom_wheel_round($1,$2,$3,false,null,null)', [id(), room, [archived]]), /รายชื่อผู้เข้าร่วม/);
  await assert.rejects(q("select public.start_classroom_wheel_round($1,$2,$3,false,'2026-11-19',1)", [id(), room, [two]]), /รายชื่อผู้เข้าร่วม/);
  const presentRound = id();
  await q("select public.start_classroom_wheel_round($1,$2,$3,false,'2026-11-19',1)", [presentRound, room, [one]]);
  assert.equal((await q('select public.spin_classroom_wheel($1,$2) as value', [presentRound, id()]))[0].value.student_id, one);
  const repeatRound = id();
  await q('select public.start_classroom_wheel_round($1,$2,$3,true,null,null)', [repeatRound, room, [one]]);
  for (let i = 0; i < 3; i++) assert.equal((await q('select public.spin_classroom_wheel($1,$2) as value', [repeatRound, id()]))[0].value.student_id, one);
  await db.exec('reset role');
  await q('delete from public.profiles where id=$1', [one]);
  assert.equal((await q('select count(*)::int as n from classroom_wheel_rounds where $1=any(participant_ids)', [one]))[0].n, 0);
  assert.equal((await q('select count(*)::int as n from classroom_wheel_draws where student_id=$1', [one]))[0].n, 0);
  assert.equal((await q('select count(*)::int as n from student_reinforcement_entries where student_id=$1', [one]))[0].n, 0);
  await db.exec('set role anon');
  await assert.rejects(q('select public.student_reinforcement_summary($1)', [two]), /permission denied/);
  console.log('PASS real Postgres engine: migration, RLS, server draw/no-repeat/repeat, idempotent start/spin/award/reversal, attendance, archived accounts, duplicate room names, private balances, direct write denial and deletion cascades');
} finally { await db.close(); }
